import { Router } from "express";
import { addCarExpense,createCar,deleteCar,deleteCarExpense,downloadCarDocument,downloadSaleDocument,getCarFinancials,getCar,listCarExpenses,listCarProfits,listCars,sellCar,updateCar,updateCarExpense,updateCarStatus,uploadCarDocument,updateCarDocuments,uploadSaleDocument } from "../controllers/carController";
import { carDocumentUpload } from "../middleware/carDocumentUpload";
import { requireAdmin } from "../middleware/auth";
const router=Router();
router.get("/",listCars);
router.get("/:id",getCar);
router.get("/expenses",requireAdmin,listCarExpenses);
router.get("/profits",requireAdmin,listCarProfits);
router.post("/",createCar);
router.patch("/:id/status",requireAdmin,updateCarStatus);
router.patch("/:id",requireAdmin,updateCar);
router.delete("/:id",requireAdmin,deleteCar);
router.get("/:id/financials",requireAdmin,getCarFinancials);
router.patch("/:id/documents",requireAdmin,updateCarDocuments);
router.post("/:id/documents/:documentKey",requireAdmin,carDocumentUpload.single("file"),uploadCarDocument);
router.post("/:id/sale/documents/:documentKey",requireAdmin,carDocumentUpload.single("file"),uploadSaleDocument);
router.get("/:id/sale/documents/:documentKey/download",requireAdmin,downloadSaleDocument);
router.get("/:id/documents/:documentKey/download",downloadCarDocument);
router.post("/:id/expenses",requireAdmin,addCarExpense);
router.patch("/expenses/:expenseId",requireAdmin,updateCarExpense);
router.patch("/:id/expenses/:expenseId",requireAdmin,updateCarExpense);
router.delete("/:id/expenses/:expenseId",requireAdmin,deleteCarExpense);
router.post("/:id/sell",requireAdmin,sellCar);
export default router;